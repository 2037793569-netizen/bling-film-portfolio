const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true, executablePath:'/usr/bin/google-chrome', args:['--no-sandbox']});
 const page = await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[]; page.on('pageerror',e=>{errors.push(String(e));console.error('PAGE ERROR',String(e));}); page.on('console',m=>{if(m.type()==='error') console.error('BROWSER',m.text());});
 await page.goto('http://127.0.0.1:8765', {waitUntil:'domcontentloaded'});
 await page.locator('#enter-now').click();
 try { await page.waitForFunction(()=>document.querySelector('#opening').currentTime>.5); } catch(e) { console.log(await page.evaluate(()=>({body:document.body.className,loaderHidden:document.querySelector('#loader').hidden,videos:[...document.querySelectorAll('video')].map(v=>({id:v.id,src:v.currentSrc,ready:v.readyState,paused:v.paused,time:v.currentTime,error:v.error?.message,codec:v.canPlayType('video/mp4; codecs=\"avc1.4D401F\"')}))}))); throw e; }
 const opening=await page.locator('#opening').evaluate(v=>({time:v.currentTime,src:v.currentSrc,paused:v.paused}));
 assert(opening.src.startsWith('blob:') && !opening.paused);
 await page.waitForTimeout(1000);
 assert(await page.locator('#opening').evaluate(v=>v.currentTime)>opening.time+.5);
 await page.locator('#skip').click();
 const stopped=await page.locator('#opening').evaluate(v=>v.currentTime);
 await page.waitForTimeout(500);
 assert(await page.locator('#opening').evaluate(v=>v.paused));
 assert(Math.abs(await page.locator('#opening').evaluate(v=>v.currentTime)-stopped)<.1);
 await page.mouse.move(900,450);
 assert.equal(await page.locator('#gaze-canvas').evaluate(c=>c.width),1280);
 await page.locator('#main-nav a[href="#about"]').click();
 await page.waitForFunction(()=>{const v=document.querySelector('#about-video');return v.currentTime>.5&&!v.paused;});
 const about=await page.locator('#about-video').evaluate(v=>({time:v.currentTime,src:v.currentSrc}));
 assert(about.src.startsWith('blob:'));
 await page.waitForTimeout(1000);
 assert(await page.locator('#about-video').evaluate(v=>v.currentTime)>about.time+.5);
 await page.mouse.wheel(0,150);
 await page.waitForTimeout(800);
 assert(await page.locator('#about-video').evaluate(v=>v.paused));
 assert(await page.locator('#stage').evaluate(e=>e.classList.contains('about-quick-finish')));
 await page.mouse.wheel(0,150);
 await page.waitForTimeout(1200);
 assert(await page.locator('#honors').evaluate(e=>Math.abs(e.getBoundingClientRect().top)<20));
 // Replay and natural ended events must still finish both films.
 await page.locator('#main-nav a[href="#cover"]').click();
 await page.waitForTimeout(1200);
 await page.locator('#replay').click();
 await page.waitForFunction(()=>!document.querySelector('#opening').paused);
 await page.locator('#opening').evaluate(v=>v.currentTime=v.duration-.25);
 await page.waitForFunction(()=>document.querySelector('#opening').classList.contains('finished'));
 await page.locator('#main-nav a[href="#about"]').click();
 await page.waitForFunction(()=>!document.querySelector('#about-video').paused);
 await page.locator('#about-video').evaluate(v=>v.currentTime=v.duration-.25);
 await page.waitForFunction(()=>document.querySelector('#about-video').paused);
 assert.equal(errors.length,0,errors.join('\n'));
 console.log('PASS: opening and about clocks advance, buffered playback, replay, natural endings, first wheel finishes film, second wheel advances; no JavaScript errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
